-- 케이스별 TTFT(첫 토큰까지의 시간) — 기존 DB 에 적용하는 마이그레이션
--
-- ELAPSED_MS 는 답변이 '끝날' 때까지의 시간이라 모델이 얼마나 길게 답했는지에
-- 좌우된다. 말이 많은 모델은 느린 모델처럼 보인다. TTFT_MS 는 답변의 첫 토큰이
-- 도착한 시점에서 시계를 멈춘 값이라, 생성 길이가 끼어들기 전의 대기 —
-- 큐 대기 + prefill — 만 담는다. 큐 혼잡은 여기에 먼저, 가장 크게 나타난다.
--
-- 엔드포인트가 text/event-stream 으로 답할 때만 값이 남는다. 한 덩어리 JSON 으로
-- 답하는 호출은 '첫 토큰'이라는 순간 자체가 없으므로 NULL 이다.
--
-- 이 마이그레이션을 돌리지 않아도 앱은 그대로 동작한다 — 컬럼이 없으면 저장만
-- 건너뛰고(실행 중 화면에는 그대로 보인다), 돌린 뒤부터 기록 탭에도 남는다.
--
-- 한 문장씩 실행할 것. 중간에 빈 줄을 넣지 말 것(SQL*Plus 가 문장을 끊는다).
-- 앱(dev 서버)이 떠 있으면 ALTER 가 ORA-00054 로 막힐 수 있으니 먼저 내린다.
-- ============================================================

ALTER TABLE PTX_RUN_DET ADD (TTFT_MS NUMBER);

COMMIT;

-- 확인 — 컬럼이 보이면 정상. 기존 행은 NULL 이고 UI 에서는 비어 보인다.
SELECT column_name, data_type FROM user_tab_columns
 WHERE table_name = 'PTX_RUN_DET' AND column_name = 'TTFT_MS';
