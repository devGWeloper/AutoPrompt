-- 6) 감사 로그에 남아 있는 옛 테이블 이름 ------------------------------------
UPDATE PTX_AUDIT_HIS
   SET TARGET_TABLE_NM = CASE TARGET_TABLE_NM
         WHEN 'PM_NODE_PROMPT_VER' THEN 'PTX_PROMPT_HIS'
         WHEN 'PM_TEST_DATASET'    THEN 'PTX_DATASET_MAS'
         WHEN 'PM_TEST_CASE'       THEN 'PTX_DATASET_DET'
         WHEN 'PM_RAGAS_RUN'       THEN 'PTX_RUN_MAS'
         WHEN 'PM_RAGAS_RESULT'    THEN 'PTX_RUN_DET'
         WHEN 'PM_AUDIT_LOG'       THEN 'PTX_AUDIT_HIS'
         ELSE TARGET_TABLE_NM
       END
 WHERE TARGET_TABLE_NM LIKE 'PM\_%' ESCAPE '\';
COMMIT;
