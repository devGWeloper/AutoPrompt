-- 3) 실행 기록이 데이터셋 삭제와 무관해지도록 ---------------------------------
--    DATASET_NM 은 실행 시점 이름 스냅샷, DATASET_ID 는 NULL 허용으로 바꾼다.
ALTER TABLE PTX_RUN_MAS ADD (DATASET_NM VARCHAR2(200));
UPDATE PTX_RUN_MAS r
   SET DATASET_NM = (SELECT d.DATASET_NM FROM PTX_DATASET_MAS d WHERE d.DATASET_ID = r.DATASET_ID)
 WHERE DATASET_NM IS NULL;
ALTER TABLE PTX_RUN_MAS MODIFY (DATASET_ID NULL);
COMMIT;

-- 4) FK 재정의 — 삭제 규칙을 제약에 박는다 -----------------------------------
--    기존 FK 는 이름이 시스템 생성(SYS_C…)일 수 있어 조회해서 전부 떨군다.
BEGIN
  FOR c IN (SELECT table_name, constraint_name
              FROM user_constraints
             WHERE constraint_type = 'R'
               AND table_name IN ('PTX_PROMPT_HIS','PTX_DATASET_DET','PTX_RUN_MAS','PTX_RUN_DET'))
  LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE '||c.table_name||' DROP CONSTRAINT '||c.constraint_name;
  END LOOP;
END;
/

ALTER TABLE PTX_PROMPT_HIS ADD CONSTRAINT FK_PTX_PROMPT_PREV
  FOREIGN KEY (PREV_PROMPT_ID) REFERENCES PTX_PROMPT_HIS(PROMPT_ID) ON DELETE SET NULL;

ALTER TABLE PTX_DATASET_DET ADD CONSTRAINT FK_PTX_DATASET_DET_MAS
  FOREIGN KEY (DATASET_ID) REFERENCES PTX_DATASET_MAS(DATASET_ID) ON DELETE CASCADE;

ALTER TABLE PTX_RUN_MAS ADD CONSTRAINT FK_PTX_RUN_MAS_PROMPT
  FOREIGN KEY (PROMPT_ID) REFERENCES PTX_PROMPT_HIS(PROMPT_ID) ON DELETE SET NULL;

ALTER TABLE PTX_RUN_MAS ADD CONSTRAINT FK_PTX_RUN_MAS_DATASET
  FOREIGN KEY (DATASET_ID) REFERENCES PTX_DATASET_MAS(DATASET_ID) ON DELETE SET NULL;

ALTER TABLE PTX_RUN_DET ADD CONSTRAINT FK_PTX_RUN_DET_MAS
