ALTER TABLE PTX_RUN_DET ADD CONSTRAINT FK_PTX_RUN_DET_CASE
  FOREIGN KEY (CASE_ID) REFERENCES PTX_DATASET_DET(CASE_ID) ON DELETE SET NULL;

