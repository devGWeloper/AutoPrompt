-- ============================================================
-- 수동 통과 처리 — 기존 DB 에 적용하는 마이그레이션
--
-- 채점은 불일치(EXACT_VAL=0)로 떨어졌지만 사람이 보고 맞다고 판단하는 경우가 있다.
-- 표현만 다르거나, 정답지 쪽이 낡았거나, 공백·순서처럼 이 테스트가 볼 필요 없는
-- 차이거나. 그때 그 케이스를 손으로 통과시키는 자리가 PASS_YN 이다.
--
-- EXACT_VAL 을 1 로 고쳐 쓰지 않는다. 기계의 판정과 사람의 판정을 한 칸에 섞으면
-- "원래 무엇이 걸렸는지" 가 사라져서, 나중에 정답지를 고쳐야 하는지 판단할 수 없다.
-- 두 값을 따로 두고, 합쳐 읽어야 하는 곳에서만 합친다:
--   실행 단위 EXACT_VAL  — 통과 처리된 케이스를 1 로 쳐서 평균낸다
--   불일치 재실행 대상   — 통과 처리된 케이스는 빠진다
--
-- 이 마이그레이션을 돌리지 않아도 앱은 그대로 동작한다 — 컬럼이 없으면 통과 버튼이
-- 서지 않고, 채점 결과만 지금처럼 보인다.
--
-- 한 문장씩 실행할 것. 중간에 빈 줄을 넣지 말 것(SQL*Plus 가 문장을 끊는다).
-- 앱(dev 서버)이 떠 있으면 ALTER 가 ORA-00054 로 막힐 수 있으니 먼저 내린다.
-- ============================================================

ALTER TABLE PTX_RUN_DET ADD (PASS_YN CHAR(1), PASS_TM TIMESTAMP);

COMMIT;

-- 확인 — 컬럼이 보이면 정상. 기존 행은 NULL(= 통과 처리한 적 없음)이다.
SELECT column_name, data_type FROM user_tab_columns
 WHERE table_name = 'PTX_RUN_DET' AND column_name IN ('PASS_YN', 'PASS_TM');
